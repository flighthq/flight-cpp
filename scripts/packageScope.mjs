// `--package=x`, `--package x` and a bare positional are all accepted; anything else is refused. Exactly one
// package, unless the caller allows a coordinated group (`pkg:generate` does), which is still a named list
// and never the whole SDK.
// `-j N`, `-jN`, `--jobs N` and `--jobs=N` all land in values as `--jobs`; parseJobs validates them.
export function parsePackageArguments(argv, { allowGroup = false, flags = [], valued = [] } = {}) {
  const result = { flags: new Set(), packages: [], values: new Map() };
  for (let index = 0; index < argv.length; index++) {
    const argument = argv[index];
    if (argument === '--package') {
      result.packages.push(argv[++index]);
    } else if (argument.startsWith('--package=')) {
      result.packages.push(argument.slice('--package='.length));
    } else if (argument === '-j' || argument === '--jobs') {
      result.values.set('--jobs', argv[++index]);
    } else if (/^-j\d+$/u.test(argument)) {
      result.values.set('--jobs', argument.slice(2));
    } else if (argument.startsWith('--jobs=')) {
      result.values.set('--jobs', argument.slice('--jobs='.length));
    } else if (flags.includes(argument)) {
      result.flags.add(argument);
    } else if (valued.some((name) => argument.startsWith(`${name}=`))) {
      const name = valued.find((candidate) => argument.startsWith(`${candidate}=`));
      result.values.set(name, argument.slice(name.length + 1));
    } else if (!argument.startsWith('-')) {
      result.packages.push(argument);
    } else {
      throw new Error(`Unknown option ${argument}`);
    }
  }
  if (result.packages.length === 0 || result.packages.includes(undefined) || (!allowGroup && result.packages.length !== 1)) {
    throw new Error(
      `Name ${allowGroup ? 'one or more packages' : 'exactly one package'}. Package-scoped commands never operate on ` +
        'the whole SDK; use the sdk:* scripts for that.',
    );
  }
  const packages = [...new Set(result.packages.map(normalizePackageName))];
  return { ...result, package: packages[0], packages };
}

export function parseJobs(raw, fallback = DEFAULT_JOBS) {
  if (raw === undefined || raw === '') return fallback;
  const jobs = Number.parseInt(String(raw), 10);
  if (!Number.isInteger(jobs) || jobs < 1 || String(jobs) !== String(raw).trim()) {
    throw new Error(`-j needs a positive integer, got ${String(raw)}`);
  }
  return jobs;
}

// Where a package's scoped reports live. Gitignored with the rest of out/, and per package so lanes
// working in parallel never overwrite each other's evidence.
export function packageOutputDirectory(root, packageName) {
  return path.join(root, 'out', 'pkg', packageName.slice(SDK_PREFIX.length));
}

// The headers a package owns in a generated tree, as include-relative paths, sorted.
export function packageHeaders(generatedRoot, packageName) {
  const directory = path.join(generatedRoot, 'include', ...includePrefixOf(packageName).split('/').filter(Boolean));
  if (!existsSync(directory)) return [];
  return filesUnder(directory)
    .map((filename) => portable(path.relative(path.join(generatedRoot, 'include'), filename)))
    .filter((header) => header.endsWith('.hpp'))
    .sort(compareText);
}

// Computes, without writing anything, every file the scoped merge changes. Returns a Map of
// generated-root-relative path -> new contents (string) or null (delete), plus what was found.
// `movingTogether` names the other packages of a coordinated group move. They are about to be merged from
// the same candidate, so an import of theirs into this package is not stranded and their old revision is
// not a stale dependency.
export function planPackageMerge({ candidateRoot, committedRoot, movingTogether = [], packageName }) {
  const group = new Set(movingTogether);
  const prefix = includePrefixOf(packageName);
  const read = (root, file) => readFileSync(path.join(root, file), 'utf8');
  const readJson = (root, file) => JSON.parse(read(root, file));
  const committedManifest = readJson(committedRoot, 'manifest.json');
  const candidateManifest = readJson(candidateRoot, 'manifest.json');
  const problems = [];

  // A slice is only meaningful against the inventory it is spliced into. The Flight revision and the
  // binding profiles may differ -- that is the mixed transition, recorded per row, and only the moved
  // row takes the candidate's -- but a different compiler or namespace mapping changes every package at
  // once and is still a whole-SDK regeneration.
  validateProvenance(committedManifest);
  if (candidateManifest.schema !== UNIFORM_MANIFEST_SCHEMA) {
    throw new Error('The candidate must be a single-revision generation; it is in the mixed form.');
  }
  validateProvenance(candidateManifest);
  for (const field of SHARED_PROVENANCE) {
    if (stableJson(committedManifest[field]) !== stableJson(candidateManifest[field])) {
      throw new Error(
        `The candidate's ${field} differs from the committed inventory's. That cannot be recorded per package; ` +
          'regenerate the whole SDK with `npm run sdk:generate` instead.',
      );
    }
  }
  for (const field of ['package', 'repository']) {
    if (committedManifest.source[field] !== candidateManifest.source[field]) {
      throw new Error(`The candidate's source.${field} differs from the committed inventory's.`);
    }
  }
  const candidateProvenance = rowProvenance(candidateManifest, {});
  const candidateRow = candidateManifest.packages.find((row) => row.package === packageName);
  if (candidateRow === undefined) throw new Error(`The candidate inventory has no row for ${packageName}.`);
  // A package that drops a module or header another package still uses cannot move alone: the dependent
  // row stays at its own revision, and would be left importing something that no longer exists.
  assertNoOrphanedDependents({ candidateRoot, committedRoot, exempt: group, packageName });
  // Closure members this run regenerated but does NOT write keep their committed revision. When that
  // differs, the package was generated against dependencies newer than the ones it will sit beside.
  const warnings = [];
  const committedByName = new Map(committedManifest.packages.map((row) => [row.package, row]));
  const closure = candidateManifest.packages
    .filter((row) => row.package !== packageName && !group.has(row.package) && committedByName.has(row.package))
    .map((row) => ({ name: row.package, provenance: rowProvenance(committedManifest, committedByName.get(row.package)) }));
  const staleClosure = closure.filter((entry) => entry.provenance.revision !== candidateProvenance.revision).map((entry) => entry.name);
  if (staleClosure.length > 0) {
    warnings.push(
      `${packageName} is now at ${candidateProvenance.revision.slice(0, 7)} but dependencies it was generated against ` +
        `remain at another revision in the inventory: ${staleClosure.join(', ')}. Move them too, or compile to confirm.`,
    );
  }
  const candidateProfiles = bindingProfileSetId(candidateProvenance.bindingProfiles);
  const otherProfiles = closure
    .filter((entry) => bindingProfileSetId(entry.provenance.bindingProfiles) !== candidateProfiles)
    .map((entry) => entry.name);
  if (otherProfiles.length > 0) {
    warnings.push(
      `${packageName} is now under the current binding profiles but dependencies it was generated against remain under ` +
        `other profiles in the inventory: ${otherProfiles.join(', ')}. Move them too, or compile to confirm.`,
    );
  }

  const writes = new Map();
  const committedHeaders = new Set(includeFilesUnder(committedRoot, prefix));
  const candidateHeaders = includeFilesUnder(candidateRoot, prefix);
  const changedHeaders = [];
  for (const header of candidateHeaders) {
    const contents = read(candidateRoot, `include/${header}`);
    if (!committedHeaders.has(header) || read(committedRoot, `include/${header}`) !== contents) {
      writes.set(`include/${header}`, contents);
      changedHeaders.push(header);
    }
    committedHeaders.delete(header);
  }
  for (const header of committedHeaders) {
    writes.set(`include/${header}`, null);
    changedHeaders.push(header);
  }
  const inPrefix = (file) => file.startsWith(prefix);
  const mergedHeaderText = (header) =>
    writes.has(`include/${header}`) ? writes.get(`include/${header}`) : read(committedRoot, `include/${header}`);

  // manifest.json -- rows carry explicit provenance while merging; finalizeProvenance picks the form.
  const manifest = structuredClone(committedManifest);
  manifest.packages = replaceSortedRows(
    manifest.packages.map((row) => ({ ...row, source: rowProvenance(committedManifest, row) })),
    (row) => row.package === packageName,
    [{ ...candidateRow, source: candidateProvenance }],
    (left, right) => compareText(left.package, right.package),
  );
  manifest.summary = {
    packages: manifest.packages.length,
    emittedModules: sum(manifest.packages, 'emittedModules'),
    refusedModules: sum(manifest.packages, 'refusedModules'),
    sourceModules: sum(manifest.packages, 'sourceModules'),
  };
  manifest.emissionRepairs = mergeRepairRecords(committedManifest.emissionRepairs, candidateManifest.emissionRepairs, inPrefix);
  manifest.sourcePatches = replaceRowsInPlace(
    committedManifest.sourcePatches ?? [],
    (patch) => patch.package === packageName,
    (candidateManifest.sourcePatches ?? []).filter((patch) => patch.package === packageName),
  );
  const aliases = committedManifest.duplicateStructuralStructAliases;
  const aliasFiles = mergeFileList(aliases.files, candidateManifest.duplicateStructuralStructAliases.files, inPrefix);
  manifest.duplicateStructuralStructAliases = {
    files: aliasFiles,
    structs: mergeAliasedStructs({
      aliasFiles,
      committedFiles: aliases.files,
      committedStructs: aliases.structs,
      committedText: (file) => read(committedRoot, `include/${file}`),
      mergedText: mergedHeaderText,
      prefix,
    }),
  };
  const includes = committedManifest.canonicalPackageLocalIncludes;
  const includeFiles = mergeFileList(
    includes.files,
    candidateManifest.canonicalPackageLocalIncludes.files,
    inPrefix,
  );
  // The total counts quoted includes the canonicalizer rewrote, and a rewritten include is
  // indistinguishable from an emitted angle include once written. Unchanged files therefore contribute
  // nothing, and a changed file contributes the difference in its own same-package angle includes,
  // which cancels every include the emitter wrote that way itself.
  let includeDelta = 0;
  for (const header of changedHeaders) {
    const old = includes.files.includes(header)
      ? samePackageIncludes(header, readIfPresent(committedRoot, `include/${header}`) ?? '')
      : 0;
    const now = includeFiles.includes(header) ? samePackageIncludes(header, writes.get(`include/${header}`) ?? '') : 0;
    includeDelta += now - old;
  }
  manifest.canonicalPackageLocalIncludes = { files: includeFiles, includes: includes.includes + includeDelta };

  // refusals.json
  const refusals = readJson(committedRoot, 'refusals.json');
  refusals.refusals = replaceSortedRows(
    refusals.refusals,
    (row) => row.package === packageName,
    readJson(candidateRoot, 'refusals.json').refusals.filter((row) => row.package === packageName),
    (left, right) => compareText(left.package, right.package),
  );
  finalizeProvenance(manifest, refusals);
  writes.set('manifest.json', `${JSON.stringify(manifest, undefined, 2)}\n`);
  writes.set('refusals.json', `${JSON.stringify(refusals, undefined, 2)}\n`);

  // best-effort.json
  if (existsSync(path.join(committedRoot, 'best-effort.json')) || existsSync(path.join(candidateRoot, 'best-effort.json'))) {
    if (!existsSync(path.join(committedRoot, 'best-effort.json')) || !existsSync(path.join(candidateRoot, 'best-effort.json'))) {
      throw new Error('Only one of the trees has best-effort.json; regenerate the whole SDK in one mode.');
    }
    const bestEffort = readJson(committedRoot, 'best-effort.json');
    // `consumers` names every module that imports this one, and a reverse dependent is by definition
    // outside the dependency closure the candidate was generated over. Those consumers are kept from the
    // committed record; consumers inside the closure are the candidate's to state.
    const closure = new Set(candidateManifest.packages.map((row) => row.package));
    const committedConsumers = new Map(
      bestEffort.modules
        .filter((row) => row.module.packageName === packageName)
        .map((row) => [row.module.source, row.consumers ?? []]),
    );
    const candidateModules = readJson(candidateRoot, 'best-effort.json')
      .modules.filter((row) => row.module.packageName === packageName)
      .map((row) => {
        const outside = (committedConsumers.get(row.module.source) ?? []).filter(
          (consumer) => !closure.has(consumerPackage(consumer)),
        );
        if (outside.length === 0 || row.consumers === undefined) return row;
        return { ...row, consumers: [...new Set([...row.consumers, ...outside])].sort(compareText) };
      });
    bestEffort.modules = replaceSortedRows(
      bestEffort.modules,
      (row) => row.module.packageName === packageName,
      candidateModules,
      (left, right) => compareText(left.module.packageName, right.module.packageName),
    );
    writes.set('best-effort.json', `${JSON.stringify(bestEffort, undefined, 2)}\n`);
  }

  // initialization.json
  const initialization = readJson(committedRoot, 'initialization.json');
  const candidateInitialization = readJson(candidateRoot, 'initialization.json');
  const owns = (module) => module.packageName === packageName;
  initialization.entries = replaceSortedRows(
    initialization.entries,
    owns,
    candidateInitialization.entries.filter(owns),
    (left, right) => compareText(left.packageName, right.packageName),
  );
  // Unlike the other ledgers these are NOT grouped by package, so each row is placed on its own.
  initialization.modules = mergeSortedRows(
    initialization.modules,
    (row) => owns(row.module),
    candidateInitialization.modules.filter((row) => owns(row.module)),
    compareInitializationModules,
  );
  // Evaluation groups are the strongly connected components of the WHOLE runtime import graph, in the
  // order the compiler's Tarjan walk emits them. They are derived, not owned by any package: the records
  // they are computed from are `entries` and each module's `dependencies`, both merged above. So they are
  // recomputed from the merged ledger exactly as the compiler computes them -- which keeps every module
  // in exactly one group however the package's module set changed. scripts/packageScope.test.mjs checks
  // that this reproduces the compiler's own groups.
  initialization.groups = evaluationGroups(initialization, group);
  writes.set('initialization.json', `${JSON.stringify(initialization, undefined, 2)}\n`);

  // Build metadata and README are pure functions of the merged tree and manifest.
  const mergedIncludeFiles = includeFilesUnder(committedRoot, '')
    .filter((file) => !(writes.has(`include/${file}`) && writes.get(`include/${file}`) === null))
    .concat(candidateHeaders.filter((file) => !existsSync(path.join(committedRoot, 'include', file))));
  const metadata = sdkBuildMetadata(mergedIncludeFiles);
  writes.set('cmake/FlightSdkHeaders.cmake', metadata.cmake);
  writes.set('BUILD.bazel', metadata.bazel);
  writes.set('README.md', readmeWithProvenance(readmeWithSummary(read(committedRoot, 'README.md'), manifest.summary), manifest));

  // The structural member table is shared vocabulary: every row key and computed cell any emitted header
  // or override uses. It is a pure function of that file set (scripts/structuralMembers.mjs), so it is
  // re-rendered from the merged tree exactly as a full run renders it -- when this package's headers
  // changed, or when an override now uses a row key the committed table lacks (an override is part of the
  // table's input, and one written after the last render would otherwise never reach it).
  const overrides = overrideHeaderFiles(REPOSITORY_ROOT);
  const committedTableKeys = existsSync(path.join(committedRoot, 'include', STRUCTURAL_MEMBERS))
    ? structuralTableKeys(read(committedRoot, `include/${STRUCTURAL_MEMBERS}`))
    : new Set();
  const overrideKeyMissing = overrides.some((file) => [...rowKeysIn(file.contents)].some((key) => !committedTableKeys.has(key)));
  if (changedHeaders.length > 0 || overrideKeyMissing) {
    const files = mergedIncludeFiles
      .filter((file) => file !== STRUCTURAL_MEMBERS)
      .map((file) => ({ contents: mergedHeaderText(file), path: file }));
    const table = structuralMemberTable(files, overrides);
    if (table.contents === undefined) {
      problems.push(`No emitted header uses a structural row key; ${STRUCTURAL_MEMBERS} was left as committed.`);
    } else {
      writes.set(`include/${STRUCTURAL_MEMBERS}`, table.contents);
    }
  }

  // Drop no-op writes so a check reports only real drift and an apply touches only what moved.
  for (const [file, contents] of [...writes]) {
    if (contents !== null && readIfPresent(committedRoot, file) === contents) writes.delete(file);
  }
  return {
    changedHeaders: changedHeaders.sort(compareText),
    problems,
    provenance: candidateProvenance,
    row: candidateRow,
    warnings,
    writes,
  };
}

function assertNoOrphanedDependents({ candidateRoot, committedRoot, exempt, packageName }) {
  const read = (root, file) => JSON.parse(readFileSync(path.join(root, file), 'utf8'));
  const key = (module) => `${module.packageName}\0${module.source}`;
  const owned = (root) =>
    new Set(
      read(root, 'initialization.json')
        .modules.filter((record) => record.module.packageName === packageName)
        .map((record) => key(record.module)),
    );
  // Only what THIS move removes. A reference that already dangles in the committed tree is earlier damage;
  // refusing on it would block every later move of the package without being about this one.
  const candidateModules = owned(candidateRoot);
  const committedModules = owned(committedRoot);
  const removed = (target) => committedModules.has(key(target)) && !candidateModules.has(key(target));
  const orphans = new Map();
  const note = (dependent, missing) => {
    if (exempt.has(dependent)) return;
    const list = orphans.get(dependent) ?? new Set();
    list.add(missing);
    orphans.set(dependent, list);
  };
  for (const record of read(committedRoot, 'initialization.json').modules) {
    if (record.module.packageName === packageName) continue;
    for (const dependency of record.dependencies) {
      if (dependency.target.packageName === packageName && removed(dependency.target)) {
        note(record.module.packageName, dependency.target.source);
      }
    }
  }
  const prefix = includePrefixOf(packageName);
  const candidateHeaders = new Set(includeFilesUnder(candidateRoot, prefix));
  const removedHeaders = new Set(includeFilesUnder(committedRoot, prefix).filter((header) => !candidateHeaders.has(header)));
  if (removedHeaders.size > 0) {
    for (const header of includeFilesUnder(committedRoot, '')) {
      if (header.startsWith(prefix)) continue;
      const text = readFileSync(path.join(committedRoot, 'include', header), 'utf8');
      for (const [, included] of text.matchAll(/^#include [<"]([^>"]+)[>"]/gmu)) {
        if (removedHeaders.has(included)) note(`@flighthq/${header.split('/')[1].replaceAll('_', '-')}`, included);
      }
    }
  }
  if (orphans.size === 0) return;
  const detail = [...orphans]
    .sort(([left], [right]) => compareText(left, right))
    .map(([dependent, missing]) => `${dependent} (uses ${[...missing].sort(compareText).join(', ')})`);
  throw new Error(
    `${packageName} cannot move alone: at the candidate revision it no longer has modules or headers that other packages ` +
      `still use at their recorded revision: ${detail.join('; ')}. Move them together, in the same change, or leave ` +
      `${packageName} where it is.`,
  );
}

// Mirrors flight-compiler's createCompilerModuleEvaluationGroups (packages/compiler-module/src/
// compilerModuleEvaluation.ts): Tarjan's algorithm over `entries` in order, following each module's RUNTIME
// dependencies in their recorded order; a group is cyclic when it has several modules or one that imports
// itself. Type-only imports link without evaluation and are not edges.
//
// `pending` names packages whose records are about to be replaced in the same coordinated move. Between
// two merges of a group, one member's old records may still import a module another member just dropped;
// those edges are skipped rather than refused, because the group's last merge recomputes over records
// that agree.
export function evaluationGroups(initialization, pending = new Set()) {
  const key = (module) => `${module.packageName}\0${module.source}`;
  const records = new Map(initialization.modules.map((record) => [key(record.module), record]));
  const runtimeDependencies = (record) =>
    record.dependencies
      .filter((dependency) => dependency.evaluation === 'runtime')
      .map((dependency) => {
        const target = records.get(key(dependency.target));
        if (target === undefined && pending.has(record.module.packageName)) return undefined;
        if (target === undefined) {
          throw new Error(`initialization.json: ${key(record.module)} imports ${key(dependency.target)}, which has no module record.`);
        }
        return target;
      })
      .filter((target) => target !== undefined);
  const groups = [];
  const indices = new Map();
  const lowLinks = new Map();
  const onStack = new Set();
  const stack = [];
  let next = 0;
  // Iterative, because the SDK graph is deep enough that recursion depth is a real risk on small stacks.
  const visit = (root) => {
    const frames = [{ dependencies: runtimeDependencies(root), position: 0, record: root }];
    const enter = (record) => {
      const id = key(record.module);
      indices.set(id, next);
      lowLinks.set(id, next);
      next += 1;
      stack.push(record);
      onStack.add(id);
    };
    enter(root);
    while (frames.length > 0) {
      const frame = frames[frames.length - 1];
      const id = key(frame.record.module);
      if (frame.position < frame.dependencies.length) {
        const dependency = frame.dependencies[frame.position++];
        const dependencyId = key(dependency.module);
        if (!indices.has(dependencyId)) {
          enter(dependency);
          frames.push({ dependencies: runtimeDependencies(dependency), position: 0, record: dependency, parent: id });
        } else if (onStack.has(dependencyId)) {
          lowLinks.set(id, Math.min(lowLinks.get(id), indices.get(dependencyId)));
        }
        continue;
      }
      frames.pop();
      if (frame.parent !== undefined) lowLinks.set(frame.parent, Math.min(lowLinks.get(frame.parent), lowLinks.get(id)));
      if (lowLinks.get(id) !== indices.get(id)) continue;
      const modules = [];
      let member;
      do {
        member = stack.pop();
        onStack.delete(key(member.module));
        modules.push(member.module);
      } while (member !== frame.record);
      groups.push({ cyclic: modules.length > 1 || frame.dependencies.includes(frame.record), modules });
    }
  };
  for (const entry of initialization.entries) {
    const record = records.get(key(entry));
    if (record === undefined) throw new Error(`initialization.json: entry ${key(entry)} has no module record.`);
    if (!indices.has(key(record.module))) visit(record);
  }
  return groups;
}

// Includes of `flight/...` headers that no include root resolves: the generated tree, the runtime's own
// include tree and the override tree, in that set. For a package that just moved, an entry here means a
// dependency it now needs is still at an older revision that does not have the header.
export function danglingIncludes(generatedRoot, packageNames, otherIncludeRoots = []) {
  const roots = [path.join(generatedRoot, 'include'), ...otherIncludeRoots];
  const exists = (header) => roots.some((root) => existsSync(path.join(root, header)));
  const result = new Map();
  for (const packageName of packageNames) {
    const missing = new Set();
    for (const header of includeFilesUnder(generatedRoot, includePrefixOf(packageName))) {
      const text = readFileSync(path.join(generatedRoot, 'include', header), 'utf8');
      for (const [, included] of text.matchAll(/^#include <(flight\/[^>]+)>/gmu)) if (!exists(included)) missing.add(included);
    }
    if (missing.size > 0) result.set(packageName, [...missing].sort(compareText));
  }
  return result;
}

// Paths, relative to the roots, whose contents differ between two trees, including files only one has.
export function treeDifferences(leftRoot, rightRoot) {
  const list = (root) =>
    existsSync(root) ? new Map(filesUnder(root).map((file) => [portable(path.relative(root, file)), file])) : new Map();
  const left = list(leftRoot);
  const right = list(rightRoot);
  const differs = [];
  for (const file of new Set([...left.keys(), ...right.keys()])) {
    if (!left.has(file) || !right.has(file) || !readFileSync(left.get(file)).equals(readFileSync(right.get(file)))) {
      differs.push(file);
    }
  }
  return differs.sort(compareText);
}

// Makes `targetRoot` match `sourceRoot`, touching only the paths that differ.
export function syncTree(sourceRoot, targetRoot) {
  const changed = treeDifferences(sourceRoot, targetRoot);
  for (const file of changed) {
    const source = path.join(sourceRoot, file);
    const target = path.join(targetRoot, file);
    if (existsSync(source)) {
      mkdirSync(path.dirname(target), { recursive: true });
      writeFileSync(target, readFileSync(source));
    } else {
      rmSync(target, { force: true });
      pruneEmptyDirectories(path.dirname(target), targetRoot);
    }
  }
  return changed;
}

// Writes a plan into the inventory: contents for a path, null to delete it (pruning emptied directories).
export function applyPackageMerge(plan, generatedRoot) {
  for (const [file, contents] of plan.writes) {
    const target = path.join(generatedRoot, file);
    if (contents === null) {
      rmSync(target, { force: true });
      pruneEmptyDirectories(path.dirname(target), path.join(generatedRoot, 'include'));
    } else {
      mkdirSync(path.dirname(target), { recursive: true });
      writeFileSync(target, contents);
    }
  }
}

function pruneEmptyDirectories(directory, stopAt) {
  let current = directory;
  while (current.startsWith(stopAt) && current !== stopAt && existsSync(current) && readdirSync(current).length === 0) {
    rmdirSync(current);
    current = path.dirname(current);
  }
}

// What `sdk:check` can honestly say about a MIXED inventory, given a full generation at the current pin.
//
// A row at the candidate's revision must be reproduced by it, package by package, through the same merge
// a lane uses -- so "reproduces" means exactly "pkg:generate --check would pass". A row at another revision
// cannot be reproduced at this pin at all; it is listed as pending, the transition's outstanding work, and
// is neither failed nor silently passed. The binding profiles are judged the same way: a row is reproduced
// only under the profiles it records, so a row whose record was refreshed without regenerating it claims
// the current profiles and FAILS here rather than passing as pending. Shared artifacts are compared only in
// the uniform form.
export function verifyMixedInventory({ candidateRoot, committedRoot }) {
  const read = (root, file) => JSON.parse(readFileSync(path.join(root, file), 'utf8'));
  const committed = read(committedRoot, 'manifest.json');
  const candidate = read(candidateRoot, 'manifest.json');
  validateProvenance(committed);
  const { bindingProfiles, revision } = rowProvenance(candidate, {});
  const profiles = bindingProfileSetId(bindingProfiles);
  const result = { failed: [], missing: [], pending: [], problems: [], reproduced: [], revision };
  const candidateNames = new Set(candidate.packages.map((row) => row.package));
  for (const row of committed.packages) {
    const recorded = rowProvenance(committed, row);
    const rowProfiles = bindingProfileSetId(recorded.bindingProfiles);
    if (recorded.revision !== revision || rowProfiles !== profiles) {
      result.pending.push({
        package: row.package,
        revision: recorded.revision,
        ...(rowProfiles === profiles ? {} : { bindingProfileSet: rowProfiles }),
      });
      continue;
    }
    if (!candidateNames.has(row.package)) {
      result.failed.push({ files: ['manifest.json'], package: row.package, reason: 'no longer generated at this pin' });
      continue;
    }
    const plan = planPackageMerge({ candidateRoot, committedRoot, packageName: row.package });
    if (plan.writes.size > 0) result.failed.push({ files: [...plan.writes.keys()], package: row.package });
    else result.reproduced.push(row.package);
    result.problems.push(...plan.problems);
  }
  const committedNames = new Set(committed.packages.map((row) => row.package));
  result.missing = candidate.packages.map((row) => row.package).filter((name) => !committedNames.has(name));
  return result;
}

// Removes every row `belongs` selects, then inserts `replacement` rows at their upper bound under
// `compare`, preserving the replacement's own relative order. When the package already had rows, they
// go back exactly where the first old row was; that is what makes a remove-and-reinsert an identity.
export function replaceSortedRows(rows, belongs, replacement, compare) {
  const firstOld = rows.findIndex(belongs);
  const kept = rows.filter((row) => !belongs(row));
  if (replacement.length === 0) return kept;
  let at;
  if (firstOld >= 0) {
    at = rows.slice(0, firstOld).filter((row) => !belongs(row)).length;
  } else {
    at = kept.findIndex((row) => compare(row, replacement[0]) > 0);
    if (at < 0) at = kept.length;
  }
  return [...kept.slice(0, at), ...replacement, ...kept.slice(at)];
}

// For a ledger sorted by a total order that interleaves packages: drop the package's rows, then place
// each replacement row at its own upper bound.
export function mergeSortedRows(rows, belongs, replacement, compare) {
  const result = rows.filter((row) => !belongs(row));
  for (const row of replacement) {
    let at = result.findIndex((existing) => compare(existing, row) > 0);
    if (at < 0) at = result.length;
    result.splice(at, 0, row);
  }
  return result;
}

// Same, for ledgers with no sort order: the replacement takes the old rows' positions one for one, and
// any surplus follows the last of them (or is appended when the package had none).
export function replaceRowsInPlace(rows, belongs, replacement) {
  const result = [];
  let next = 0;
  let lastOld = -1;
  for (const row of rows) {
    if (belongs(row)) {
      if (next < replacement.length) result.push(replacement[next++]);
      lastOld = result.length;
    } else {
      result.push(row);
    }
  }
  const rest = replacement.slice(next);
  if (rest.length === 0) return result;
  const at = lastOld < 0 ? result.length : lastOld;
  return [...result.slice(0, at), ...rest, ...result.slice(at)];
}

// Module evaluation records are ordered by module name, then package, then source, in code-unit order.
export function compareInitializationModules(left, right) {
  return (
    compareText(left.module.name, right.module.name) ||
    compareText(left.module.packageName, right.module.packageName) ||
    compareText(left.module.source, right.module.source)
  );
}

// File lists are sorted except where a repair recorded them in emission order, so the package's files
// go back where its old ones were, and only a package new to the list is placed by sort order.
function mergeFileList(committed, candidate, inPrefix) {
  return replaceSortedRows(committed, inPrefix, candidate.filter(inPrefix), compareText);
}

function mergeRepairRecords(committed, candidate, inPrefix) {
  const candidateById = new Map(candidate.map((record) => [record.id, record]));
  const merged = committed.map((record) => ({
    files: mergeFileList(record.files, candidateById.get(record.id)?.files ?? [], inPrefix),
    id: record.id,
  }));
  const known = new Set(committed.map((record) => record.id));
  // A repair declared since the inventory was last generated in full is shared drift, not this package's;
  // it joins only when it actually touched the package, and then only with the package's files.
  for (const record of candidate) {
    if (known.has(record.id)) continue;
    const files = record.files.filter(inPrefix);
    if (files.length > 0) merged.push({ files, id: record.id });
  }
  return merged;
}

// `structs` names every struct the alias pass turned into an alias anywhere. A name stays when some
// aliased file outside the package still aliases it (or when it cannot be found textually at all, so a
// pattern this function does not recognize never deletes a fact), and the package's own aliases join.
function mergeAliasedStructs({ aliasFiles, committedFiles, committedStructs, committedText, mergedText, prefix }) {
  const aliasedIn = (text) => new Set([...text.matchAll(/\busing (\w+) = flight::types::\1;/gu)].map((match) => match[1]));
  const outside = new Set();
  const seenCommitted = new Set();
  for (const file of committedFiles) {
    const names = aliasedIn(committedText(file));
    for (const name of names) seenCommitted.add(name);
    if (!file.startsWith(prefix)) for (const name of names) outside.add(name);
  }
  const result = new Set(committedStructs.filter((name) => outside.has(name) || !seenCommitted.has(name)));
  for (const file of aliasFiles.filter((candidate) => candidate.startsWith(prefix))) {
    for (const name of aliasedIn(mergedText(file) ?? '')) result.add(name);
  }
  return [...result].sort(compareText);
}

// `@flighthq/camera-controls/packages/camera-controls/src/x.ts` -> `@flighthq/camera-controls`.
