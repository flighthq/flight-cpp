// Package-scoped edits to the committed SDK inventory.
//
// `sdk:generate` rewrites the whole generated/ tree, which costs a full-SDK compile and lands every
// package's drift at once. A package owner needs the opposite: regenerate ONE package, and change
// nothing that package does not own. Generation still has to see the package's dependency closure --
// compiling @flighthq/math against nothing measures the omission, not math -- so the candidate tree is
// produced over the closure and then only the requested package's slice of it is carried across:
//
//   include/flight/<package>/**         replaced wholesale (files the candidate no longer emits go)
//   manifest.json                       the package's row, and the package's share of each per-file list
//   refusals.json, best-effort.json     the package's rows
//   initialization.json                 the package's entries and modules; groups are recomputed
//   cmake/FlightSdkHeaders.cmake,
//   BUILD.bazel, README.md,
//   flight/sdk/structural_members.hpp   re-derived from the merged tree, never from the candidate
//
// The repair identity proof is built from the whole declaration file and is not rewritten here.
//
// Every ordered ledger is merged by removing the package's rows and re-inserting the candidate's at the
// position a full run would put them. That claim is checked, not assumed: scripts/packageScope.test.mjs
// removes and re-inserts every package of the committed tree and requires the result to be byte-identical.

// The repository this script belongs to, whose override tree contributes to the structural member table.
const REPOSITORY_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const SDK_PREFIX = '@flighthq/';
export const STRUCTURAL_MEMBERS = 'flight/sdk/structural_members.hpp';
export const DEFAULT_JOBS = 2;
export const UNIFORM_MANIFEST_SCHEMA = 'flight-generated-sdk/1';
export const MIXED_MANIFEST_SCHEMA = 'flight-generated-sdk/2';
export const UNIFORM_REFUSALS_SCHEMA = 'flight-generated-sdk-refusals/2';
export const MIXED_REFUSALS_SCHEMA = 'flight-generated-sdk-refusals/3';

// Mixed-pin transition.
//
// A pin move changes every package, but lanes move their packages one at a time. Rather than force a
// whole-SDK regeneration, the inventory may be MIXED while a pin moves: each package row then states the
// Flight revision (and SDK version) its output was generated from, and nothing claims a single revision
// for the tree. The binding profiles are recorded the same way, because a profile change is the same
// kind of event: it changes the emission of exactly the packages that reach the changed bindings, and a
// lane moves its own packages under the new profile one at a time. A global refresh of the recorded
// digests would claim that every untouched row was generated under bindings it never saw, so the
// profile a row was generated under stays on that row until the row itself is regenerated. The compiler
// and the namespace mapping are not representable per package -- a row generated by another compiler
// would not link against its neighbours -- so a difference there is still refused.
//
// The two forms:
//   uniform  schema flight-generated-sdk/1. `source.revision`/`source.version` and `bindingProfiles` are
//            global, rows carry neither `source` nor `bindingProfileSet`, refusals.json carries
//            `sourceRevision`. Byte-identical to what sdk:generate writes.
//   mixed    schema flight-generated-sdk/2. `source` keeps package/repository and lists the distinct
//            `revisions`; EVERY row carries `source: { revision, version }`; refusals.json (schema
//            flight-generated-sdk-refusals/3) lists `sourceRevisions`. When every row was generated under
//            one profile list it stays global as `bindingProfiles`; otherwise `bindingProfileSets` lists
//            each distinct list under its content digest and EVERY row names its set in
//            `bindingProfileSet`.
//
// A uniform manifest is read as every row at the global revision and profiles, which is the migration:
// the first scoped run at a new pin or profile turns it mixed. The form is recomputed after every merge,
// so when the last row reaches the new revision and profiles the inventory collapses back to the uniform
// form on its own.

// The revision, version and binding profiles a row was generated from, whichever form the manifest is in.
// A row whose profile record is missing or names no listed set is refused rather than read as current.
export function rowProvenance(manifest, row) {
  const source = row.source !== undefined ? row.source : manifest.source;
  return { bindingProfiles: rowBindingProfiles(manifest, row), revision: source.revision, version: source.version };
}

// The content address of one binding-profile list: a set is named by exactly what it contains, so two
// rows share a set only if they were generated under byte-identical profile records.
export function bindingProfileSetId(profiles) {
  return `sha256:${createHash('sha256').update(stableJson(profiles)).digest('hex')}`;
}

export function isMixedManifest(manifest) {
  return manifest.schema === MIXED_MANIFEST_SCHEMA;
}

// Refuses a manifest whose provenance is incomplete or inconsistent with its own form.
export function validateProvenance(manifest) {
  const complete = (value) =>
    value !== undefined && /^[0-9a-f]{40}$/u.test(String(value.revision)) && typeof value.version === 'string' && value.version.length > 0;
  const rowsNamingSets = manifest.packages.filter((row) => row.bindingProfileSet !== undefined).map((row) => row.package);
  if (manifest.schema === UNIFORM_MANIFEST_SCHEMA) {
    if (!complete(manifest.source)) throw new Error('The uniform manifest has no complete source revision and version.');
    const stray = manifest.packages.filter((row) => row.source !== undefined).map((row) => row.package);
    if (stray.length > 0) throw new Error(`A uniform manifest cannot carry per-row provenance: ${stray.join(', ')}.`);
    if (!Array.isArray(manifest.bindingProfiles)) throw new Error('The uniform manifest records no binding profiles.');
    if (manifest.bindingProfileSets !== undefined || rowsNamingSets.length > 0) {
      throw new Error('A uniform manifest cannot carry per-row binding profiles.');
    }
    return;
  }
  if (manifest.schema !== MIXED_MANIFEST_SCHEMA) throw new Error(`Unknown generated SDK manifest schema ${String(manifest.schema)}.`);
  const incomplete = manifest.packages.filter((row) => !complete(row.source)).map((row) => row.package);
  if (incomplete.length > 0) {
    throw new Error(`Mixed manifest rows without complete provenance (revision and version): ${incomplete.join(', ')}.`);
  }
  const revisions = [...new Set(manifest.packages.map((row) => row.source.revision))].sort(compareText);
  if (stableJson(revisions) !== stableJson(manifest.source.revisions)) {
    throw new Error('The mixed manifest`s source.revisions does not list exactly the revisions its rows carry.');
  }
  const sets = validateBindingProfileSets(manifest, rowsNamingSets);
  if (revisions.length < 2 && sets < 2) throw new Error('A mixed manifest whose rows agree must be written in the uniform form.');
}

// Checks the binding-profile half of a mixed manifest and returns how many distinct profile lists it
// records. Either one global list and no row names a set, or at least two content-addressed sets and
// every row names exactly one of them; anything between is ambiguous about what a row was generated under.
function validateBindingProfileSets(manifest, rowsNamingSets) {
  if (manifest.bindingProfileSets === undefined) {
    if (!Array.isArray(manifest.bindingProfiles)) throw new Error('The mixed manifest records no binding profiles.');
    if (rowsNamingSets.length > 0) {
      throw new Error(`Rows name a binding-profile set the manifest does not list: ${rowsNamingSets.join(', ')}.`);
    }
    return 1;
  }
  if (manifest.bindingProfiles !== undefined) {
    throw new Error('The mixed manifest records both global binding profiles and per-row sets; a row`s profiles are ambiguous.');
  }
  const sets = manifest.bindingProfileSets;
  if (!Array.isArray(sets) || sets.length < 2) {
    throw new Error('Per-row binding-profile sets need at least two distinct sets; one set is written as global bindingProfiles.');
  }
  const ids = sets.map((set) => set.id);
  if (stableJson(ids) !== stableJson([...new Set(ids)].sort(compareText))) {
    throw new Error('bindingProfileSets must list distinct set ids in code-unit order.');
  }
  for (const set of sets) {
    if (!Array.isArray(set.profiles) || bindingProfileSetId(set.profiles) !== set.id) {
      throw new Error(`Binding-profile set ${String(set.id)} is not the digest of the profiles it lists.`);
    }
  }
  const missing = manifest.packages.filter((row) => !ids.includes(row.bindingProfileSet)).map((row) => row.package);
  if (missing.length > 0) {
    throw new Error(`Mixed manifest rows without a listed binding-profile set: ${missing.join(', ')}.`);
  }
  const unused = ids.filter((id) => !manifest.packages.some((row) => row.bindingProfileSet === id));
  if (unused.length > 0) throw new Error(`Binding-profile sets no row was generated under: ${unused.join(', ')}.`);
  return sets.length;
}

// Rewrites the manifest's and refusal ledger's provenance into whichever form the rows call for. `rows`
// already carry explicit `source` provenance; a `source` without `bindingProfiles` keeps the profiles the
// row already records.
export function finalizeProvenance(manifest, refusals) {
  const provenance = manifest.packages.map((row) => ({
    bindingProfiles: row.source.bindingProfiles ?? rowBindingProfiles(manifest, row),
    revision: row.source.revision,
    version: row.source.version,
  }));
  const sources = new Map(provenance.map((value) => [stableJson({ revision: value.revision, version: value.version }), value]));
  const profileSets = new Map(provenance.map((value) => [bindingProfileSetId(value.bindingProfiles), value.bindingProfiles]));
  const strip = (row) => {
    const { bindingProfileSet: _set, source: _source, ...rest } = row;
    return rest;
  };
  const { package: sourcePackage, repository } = manifest.source;
  if (sources.size === 1 && profileSets.size === 1) {
    const [only] = sources.values();
    manifest.schema = UNIFORM_MANIFEST_SCHEMA;
    manifest.source = { package: sourcePackage, repository, revision: only.revision, version: only.version };
    manifest.packages = manifest.packages.map(strip);
    refusals.schema = UNIFORM_REFUSALS_SCHEMA;
    const { sourceRevisions: _ignored, refusals: rows, compilerRevision } = refusals;
    for (const key of Object.keys(refusals)) delete refusals[key];
    Object.assign(refusals, { schema: UNIFORM_REFUSALS_SCHEMA, compilerRevision, sourceRevision: only.revision, refusals: rows });
  } else {
    const revisions = [...new Set(provenance.map((value) => value.revision))].sort(compareText);
    manifest.schema = MIXED_MANIFEST_SCHEMA;
    manifest.source = { package: sourcePackage, repository, revisions };
    manifest.packages = manifest.packages.map((row, index) =>
      withRowSource(strip(row), provenance[index], profileSets.size === 1 ? undefined : bindingProfileSetId(provenance[index].bindingProfiles)),
    );
    const { refusals: rows, compilerRevision } = refusals;
    for (const key of Object.keys(refusals)) delete refusals[key];
    Object.assign(refusals, { schema: MIXED_REFUSALS_SCHEMA, compilerRevision, sourceRevisions: revisions, refusals: rows });
  }
  // The profile record keeps the position sdk:generate gives `bindingProfiles`, in whichever form.
  const profileRecord =
    profileSets.size === 1
      ? ['bindingProfiles', [...profileSets.values()][0]]
      : [
          'bindingProfileSets',
          [...profileSets].sort(([left], [right]) => compareText(left, right)).map(([id, profiles]) => ({ id, profiles })),
        ];
  const entries = [];
  let placed = false;
  for (const [key, value] of Object.entries(manifest)) {
    if (key === 'bindingProfiles' || key === 'bindingProfileSets') {
      if (!placed) entries.push(profileRecord);
      placed = true;
    } else {
      entries.push([key, value]);
    }
  }
  if (!placed) entries.push(profileRecord);
  // `schema` stays the first key, as sdk:generate writes it.
  const ordered = { schema: manifest.schema, ...Object.fromEntries(entries) };
  for (const key of Object.keys(manifest)) delete manifest[key];
  Object.assign(manifest, ordered);
}

// Rows keep their keys in code-unit order, as the generator writes them; `bindingProfileSet` sorts first
// and `source` sorts before `sourceModules`.
function withRowSource(row, source, bindingProfileSet) {
  const entries = [...Object.entries(row), ['source', { revision: source.revision, version: source.version }]];
  if (bindingProfileSet !== undefined) entries.push(['bindingProfileSet', bindingProfileSet]);
  return Object.fromEntries(entries.sort(([left], [right]) => compareText(left, right)));
}

function rowBindingProfiles(manifest, row) {
  if (row.bindingProfileSet !== undefined) {
    const set = (manifest.bindingProfileSets ?? []).find((candidate) => candidate.id === row.bindingProfileSet);
    if (set === undefined) throw new Error(`${String(row.package)} names binding-profile set ${row.bindingProfileSet}, which the manifest does not list.`);
    return set.profiles;
  }
  if (manifest.bindingProfileSets !== undefined) {
    throw new Error(`${String(row.package)} names no binding-profile set, so the profiles it was generated under are unknown.`);
  }
  if (!Array.isArray(manifest.bindingProfiles)) throw new Error('The manifest records no binding profiles.');
  return manifest.bindingProfiles;
}

// The fields that cannot vary per package. A difference in any of them is a whole-SDK change.
const SHARED_PROVENANCE = ['compiler', 'namespaceMapping'];

export function normalizePackageName(name) {
  const trimmed = String(name ?? '').trim();
  if (trimmed.length === 0) throw new Error('Name a package, e.g. @flighthq/math or math.');
  return trimmed.startsWith(SDK_PREFIX) ? trimmed : `${SDK_PREFIX}${trimmed}`;
}

export function cppPackageName(packageName) {
  return packageName.slice(SDK_PREFIX.length).replaceAll('-', '_');
}

export function includePrefixOf(packageName) {
  return `flight/${cppPackageName(packageName)}/`;
}

