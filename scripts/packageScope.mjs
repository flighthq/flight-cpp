// Mirrors scripts/sdkGeneration.mjs#writeSdkBuildMetadata: every emitted header sorted, then the
// structural member table, which that script writes after the compiler's files.
export function sdkBuildMetadata(includeFiles) {
  const headers = includeFiles.filter((file) => file !== STRUCTURAL_MEMBERS).sort(compareText);
  headers.push(STRUCTURAL_MEMBERS);
  const cmakeHeaders = headers.map((header) => `  "\${CMAKE_CURRENT_LIST_DIR}/../include/${header}"`).join('\n');
  const bazelHeaders = headers.map((header) => `        "include/${header}",`).join('\n');
  return {
    bazel: `# Generated from the Flight SDK package graph. Do not edit.\nload("@rules_cc//cc:defs.bzl", "cc_library")\n\npackage(default_visibility = ["//visibility:public"])\n\ncc_library(\n    name = "sdk_preview",\n    hdrs = [\n${bazelHeaders}\n    ],\n    strip_include_prefix = "include",\n    deps = ["//:cpp"],\n)\n`,
    cmake: `# Generated from the Flight SDK package graph. Do not edit.\nset(FLIGHT_SDK_GENERATED_HEADERS\n${cmakeHeaders}\n)\n`,
  };
}

export function readmeWithSummary(readme, summary) {
  const pattern = /The current compiler emitted \d+ of \d+ source modules from\n\d+ SDK packages and refused \d+\./u;
  if (!pattern.test(readme)) throw new Error('generated/README.md no longer carries the summary sentence this script updates.');
  return readme.replace(
    pattern,
    `The current compiler emitted ${String(summary.emittedModules)} of ${String(summary.sourceModules)} source modules from\n` +
      `${String(summary.packages)} SDK packages and refused ${String(summary.refusedModules)}.`,
  );
}

// The README's opening provenance sentence, in the manifest's form. The uniform text is exactly the one
// scripts/sdkGeneration.mjs#generatedReadme writes, so a collapsed inventory reads as a full run's.
export function readmeWithProvenance(readme, manifest) {
  const pattern = /^This directory is generated from [\s\S]*?\nDo not edit it by hand\.$/mu;
  if (!pattern.test(readme)) throw new Error('generated/README.md no longer carries the provenance sentence this script updates.');
  const compilerRevision = manifest.compiler.revision;
  let text;
  // A manifest mixed only in its binding profiles still has one Flight revision, stated as a full run does.
  const single = !isMixedManifest(manifest)
    ? manifest.source
    : manifest.source.revisions.length === 1
      ? manifest.packages[0].source
      : undefined;
  if (single !== undefined) {
    text =
      `This directory is generated from \`${manifest.source.package}\` ${single.version} at\n` +
      `\`${single.revision}\` by \`flight-compiler\` at \`${compilerRevision}\`.\nDo not edit it by hand.`;
  } else {
    const counts = manifest.source.revisions.map((revision) => {
      const count = manifest.packages.filter((row) => row.source.revision === revision).length;
      return `- \`${revision}\` (${String(count)} package${count === 1 ? '' : 's'})`;
    });
    text =
      `This directory is generated from \`${manifest.source.package}\` during a pin transition, so its packages come from\n` +
      `different Flight revisions, each recorded on its row in \`manifest.json\`:\n\n${counts.join('\n')}\n\n` +
      `Every package was emitted by \`flight-compiler\` at \`${compilerRevision}\`.\nDo not edit it by hand.`;
  }
  return readmeWithProfiles(readme.replace(pattern, text), manifest);
}

// The README's binding-profile sentence, in the manifest's form. The global text is exactly the one
// scripts/sdkGeneration.mjs#generatedReadme writes.
function readmeWithProfiles(readme, manifest) {
  const pattern =
    /^(?:Applied binding profiles: [^\n]*?|No external binding profile is applied; this is the portable floor\.|Binding profiles differ between packages[\s\S]*?)\s+Exact profile paths and SHA-256 digests are recorded[^\n]*$/mu;
  if (!pattern.test(readme)) throw new Error('generated/README.md no longer carries the binding-profile sentence this script updates.');
  let text;
  if (manifest.bindingProfileSets === undefined) {
    const profiles =
      manifest.bindingProfiles.length === 0
        ? 'No external binding profile is applied; this is the portable floor.'
        : `Applied binding profiles: ${manifest.bindingProfiles.map((profile) => `\`${profile.identity}\``).join(', ')}.`;
    text = `${profiles} Exact profile paths and SHA-256 digests are recorded in \`manifest.json\`.`;
  } else {
    const sets = manifest.bindingProfileSets.map((set) => {
      const count = manifest.packages.filter((row) => row.bindingProfileSet === set.id).length;
      return `- \`${set.id}\` (${String(count)} package${count === 1 ? '' : 's'})`;
    });
    text =
      'Binding profiles differ between packages during a profile transition, so each package row names the profile\n' +
      `set it was generated under:\n\n${sets.join('\n')}\n\n` +
      'Exact profile paths and SHA-256 digests are recorded per set in `manifest.json`.';
  }
  return readme.replace(pattern, text);
}

export function structuralTableKeys(contents) {
  return new Set(
    [...contents.matchAll(/Key::name\.view\(\) == std::string_view\(("(?:[^"\\]|\\.)*")\)/gu)].map((match) =>
      JSON.parse(match[1]),
    ),
  );
}

export function rowKeysIn(contents) {
  return new Set(
    [...contents.matchAll(/flight::RowKey<"((?:[^"\\]|\\.)*)">/gu)].map((match) => JSON.parse(`"${match[1]}"`)),
  );
}

function includeFilesUnder(generatedRoot, prefix) {
  const includeRoot = path.join(generatedRoot, 'include');
  const directory = path.join(includeRoot, ...prefix.split('/').filter(Boolean));
  if (!existsSync(directory)) return [];
  return filesUnder(directory)
    .map((filename) => portable(path.relative(includeRoot, filename)))
    .sort(compareText);
}

function readIfPresent(root, file) {
  const filename = path.join(root, file);
  return existsSync(filename) ? readFileSync(filename, 'utf8') : undefined;
}

export function filesUnder(directory) {
  const files = [];
  for (const entry of readdirSync(directory).sort()) {
    const filename = path.join(directory, entry);
    const status = lstatSync(filename);
    if (status.isSymbolicLink()) continue;
    if (status.isDirectory()) files.push(...filesUnder(filename));
    else files.push(filename);
  }
  return files;
}

function sum(rows, field) {
  return rows.reduce((total, row) => total + row[field], 0);
}

function stableJson(value) {
  return JSON.stringify(value ?? null);
}

export function portable(filename) {
  return filename.split(path.sep).join('/');
}

export function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}
